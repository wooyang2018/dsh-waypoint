/*
 * End-to-end check of the code-review and changes surfaces on a real remote host.

Why this exists
---------------
Unit tests drive the adapters with fakes, so they prove an adapter matches the
shapes it was written against. They cannot prove that the *real* consumer — the
Forge panel the sidebar renders — is satisfied, because they never run its code.

This harness closes that gap. It imports the Forge package's own
`inspectCheckout`, `listBranches`, `hasBranch`, `localDiff`, `localText`,
`localChanges` and `baseBranches` from the sources shipped inside the DSH
runtime on the test host, and drives them through this plugin's real adapters
(`packages/local-plugin/src/remote/{fs,subprocess,sandbox}.ts`) against a real
checkout with real pending changes.

It found two defects that the unit suite could not:
  * a missing `.gitattributes` failed every diff, because the adapter rethrew the
    protocol's `workspace-file/not-found` where consumers require
    `FsError` + `FS_NOT_FOUND`;
  * `readBytes`'s own `fileStat` was the call site that actually surfaced it.

Usage
-----
On the test host, with a DSH runtime that ships the Forge sources:

    WP_FORGE_SRC=<dsh>/node_modules/@deepseek-ai/dsh-experimental-client-ui-forge/src \\
    WP_REMOTE_ROOT=/path/to/checkout \\
    WP_ANCHOR=/tmp/empty-anchor \\
    WP_AGENT_PORT=<port from agent.json> \\
    WP_AGENT_TOKEN=<token from agent.json> \\
    node --experimental-strip-types e2e-review.mjs

The Forge sources must be copied *out* of `node_modules` first: Node refuses to
strip types for a file under it.

Requirements on the checkout, so every assertion has something to see:
  * a `main` branch pushed to `origin`, with `refs/remotes/origin/HEAD` set
    (`git remote set-head origin main`) — the panel needs it to find the fork
    point, exactly as a normal clone provides;
  * a `feature` branch that changes a tracked file;
  * one staged change, one unstaged change, one untracked file;
  * optionally a non-ASCII filename, which is what a dropped `core.quotePath`
    would mangle.

This is a manual harness, not part of `pnpm test`: it needs a reachable host.
The equivalent assertions that do not need one live in
`packages/local-plugin/test/remote-*.test.ts`.
 */
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
// Generated by `node scripts/e2e-review/bundle-adapters.mjs`.
const adapters = join(here, 'adapters')
const { installRemoteFileSystem } = await import(`file://${join(adapters, 'fs.mjs')}`)
const { installRemoteSubprocess } = await import(`file://${join(adapters, 'subprocess.mjs')}`)
const { installRemoteConfine } = await import(`file://${join(adapters, 'sandbox.mjs')}`)

/**
 * @typedef {{ stdout?: string }} GitResult
 * @typedef {{ path: string, hunks?: ReadonlyArray<{ lines: ReadonlyArray<string> }> }} DiffFile
 * @typedef {{ files: ReadonlyArray<DiffFile> }} DiffResult
 * @typedef {{ route: string, body: unknown }} AgentCall
 * @typedef {{ code?: string, details?: unknown }} ProtocolFailure
 */

const FORGE = process.env.WP_FORGE_SRC
const REMOTE_ROOT = process.env.WP_REMOTE_ROOT
const ANCHOR = process.env.WP_ANCHOR
const PORT = process.env.WP_AGENT_PORT
const TOKEN = process.env.WP_AGENT_TOKEN
const HOST_ID = 'e2e-host'

/**
 * Narrow an environment value the guard above proved present.
 * @param {string | undefined} value - the raw value.
 * @returns {string} the value, as a string.
 */
const required = (value) => {
  if (value === undefined || value === '') throw new Error('missing environment value')
  return value
}

// Required: every one of these addresses the test host.
for (const [name, value] of Object.entries({ WP_FORGE_SRC: FORGE, WP_REMOTE_ROOT: REMOTE_ROOT,
  WP_ANCHOR: ANCHOR, WP_AGENT_PORT: PORT, WP_AGENT_TOKEN: TOKEN })) {
  if (value === undefined || value === '') {
    console.error(`missing ${name}; see the header of this file`)
    process.exit(1)
  }
}


const { inspectCheckout, listBranches, hasBranch, gitIn } = await import(`${FORGE}/git.ts`)
const { localDiff, localText, localChanges, baseBranches } = await import(`${FORGE}/local-diff.ts`)

/**
 * One agent call, over the same authenticated route the plugin's client uses.
 * @param {string} route - agent route path, without the API prefix.
 * @param {unknown} body - JSON request body.
 * @returns {Promise<any>} the route's `data` payload.
 */
async function agent(route, body) {
  const response = await fetch(`http://127.0.0.1:${required(PORT)}/dsh-waypoint-agent/api/v1/${route}`, {
    method: 'POST',
    headers: {
      authorization: `Bearer ${required(TOKEN)}`,
      'x-dsh-waypoint-protocol': '1',
      'content-type': 'application/json',
    },
    body: JSON.stringify(body),
  })
  /** @type {any} */
  const parsed = await response.json()
  if (!parsed.ok) {
    // Mirror the real client: the protocol code lives on `.code`, which is what
    // the adapters classify on. A bare Error would hide the distinction under test.
    /** @type {Error & ProtocolFailure} */
    const error = new Error(`${parsed.error.code}: ${parsed.error.message}`)
    error.code = parsed.error.code
    error.details = parsed.error.details
    throw error
  }
  return parsed.data
}

const mirrors = {
  /** @param {string} p @returns {{ hostId: string, remoteRoot: string, anchor: string } | undefined} */
  remoteFileContext: (p) => (p === ANCHOR || p.startsWith(`${ANCHOR}/`)
    ? { hostId: HOST_ID, remoteRoot: required(REMOTE_ROOT), anchor: required(ANCHOR) }
    : undefined),
  /** @param {string} p @returns {{ hostId: string, remoteRoot: string, anchor: string } | undefined} */
  remoteContextForRemotePath: (p) => (p === REMOTE_ROOT || p.startsWith(`${REMOTE_ROOT}/`)
    ? { hostId: HOST_ID, remoteRoot: required(REMOTE_ROOT), anchor: required(ANCHOR) }
    : undefined),
}

const hosts = {
  supportsAgent: () => true,
  agentFor: () => ({
    /** @param {unknown} request */
    gitExec: (request) => agent('git', request),
    /** @param {string} p */
    fileStat: (p) => agent('files/stat', { path: p }),
    /** @param {string} p @param {number} [offset] @param {number} [limit] */
    fileRead: (p, offset = 1, limit = 2000) => agent('files/read', { path: p, offset, limit }),
    /** @param {string} p @param {number} [offset] @param {number} [length] */
    fileBytes: (p, offset = 0, length = 5_000_000) => agent('files/bytes', { path: p, offset, length }),
    /** @param {string} p */
    fileList: (p) => agent('files/list', { path: p }),
  }),
}

/** Any service call the adapters do not claim must fail loudly, not degrade. */
/**
 * Fail loudly if a service call reached the stock provider.
 * @param {string} what - the service method name, for the message.
 * @returns {() => Promise<never>} a function that always throws.
 */
const unrouted = (what) => async () => { throw new Error(`UNROUTED: stock ${what} was reached`) }
const stockFs = {
  resolve: unrouted('fs.resolve'), processPath: unrouted('fs.processPath'),
  stat: unrouted('fs.stat'), lstat: unrouted('fs.lstat'),
  readText: unrouted('fs.readText'), readBytes: unrouted('fs.readBytes'),
  readByteRange: unrouted('fs.readByteRange'), listDir: unrouted('fs.listDir'),
}
const stockSubprocess = {
  /** @param {string} c */
  resolveExecutable: async (c) => c,
  /** @param {{ cwd: string }} spec */
  spawn: (spec) => { throw new Error(`UNROUTED: stock subprocess.spawn (cwd=${spec.cwd})`) },
}
const stockSandbox = { confine: unrouted('sandbox.confine') }

// Cordis exposes services as properties on the context; `ctx.get` is the same lookup.
const services = { fs: stockFs, subprocess: stockSubprocess, sandbox: stockSandbox }
const ctx = {
  /** @param {string} n */
  get: (n) => services[/** @type {'fs' | 'subprocess' | 'sandbox'} */ (n)],
  fs: stockFs,
  subprocess: stockSubprocess,
  sandbox: stockSandbox,
  logger: { warn() {}, debug() {}, info() {}, error() {} },
  sandboxPolicy: { resolve: () => ({ mode: 'danger-full-access', workspaceRoot: ANCHOR }) },
}

installRemoteFileSystem(ctx, mirrors, hosts)
installRemoteSubprocess(ctx, mirrors, hosts)
installRemoteConfine(ctx, mirrors)
ctx.fs = services.fs
ctx.subprocess = services.subprocess
ctx.sandbox = services.sandbox

const config = {
  gitCommand: 'git', gitTimeoutMs: 20_000, graceMs: 1_000,
  maxOutputBytes: 1_048_576, maxDiffBytes: 8_388_608,
  maxBranches: 50, maxCommits: 50, maxUntrackedFiles: 50,
}
const session = { id: 'review-session' }
const signal = new AbortController().signal
/** @param {ReadonlyArray<DiffFile>} files */
const layers = { classify: (/** @type {ReadonlyArray<DiffFile>} */ files) => files }

let failures = 0
/**
 * Record one assertion.
 * @param {string} label - what was checked.
 * @param {boolean} ok - whether it held.
 * @param {string} [detail] - observed value, shown on failure.
 */
const check = (label, ok, detail = '') => {
  if (!ok) failures += 1
  console.log(`  ${ok ? 'PASS' : 'FAIL'}  ${label}${detail ? `   [${detail}]` : ''}`)
}

console.log(`remote checkout: ${REMOTE_ROOT}`)
console.log(`forge source   : ${FORGE}\n`)

console.log('checkout header')
const inspection = await inspectCheckout(ctx, config, session, REMOTE_ROOT, signal)
check('found a checkout (not "cannot read Git")', inspection !== undefined)
check('root is the remote absolute path', inspection?.checkout.root === REMOTE_ROOT, String(inspection?.checkout.root))
check('branch reported', typeof inspection?.checkout.branch === 'string', String(inspection?.checkout.branch))
check('commit is a short sha', /^[0-9a-f]{7,}$/.test(inspection?.checkout.commit ?? ''), String(inspection?.checkout.commit))
check('linked-worktree flag is boolean', typeof inspection?.checkout.linked === 'boolean', String(inspection?.checkout.linked))

console.log('\nbranch picker')
const branches = await listBranches(ctx, config, session, REMOTE_ROOT, 50, signal)
check('current branch reported', branches.current === inspection?.checkout.branch, String(branches.current))
check('branches list is non-empty', branches.branches.length > 0, JSON.stringify(branches.branches))
check('hasBranch(current) is true', (await hasBranch(ctx, config, session, REMOTE_ROOT, branches.current ?? '', signal)) === true)
check('hasBranch(absent) is false', (await hasBranch(ctx, config, session, REMOTE_ROOT, 'no-such-branch', signal)) === false)

console.log('\nlocal changes card')
const summary = await localChanges(ctx, config, session, inspection, null, signal)
check('summary produced for the branch scope', summary !== null, String(summary))
const summaryPaths = (summary?.files ?? []).map(/** @param {DiffFile} f */ f => f.path).sort()
check('summary lists the pending files', summaryPaths.length > 0, JSON.stringify(summaryPaths))

console.log('\nper-file diffs')
const unstaged = await localDiff(ctx, config, session, REMOTE_ROOT, null, { kind: 'unstaged' }, layers, signal)
check('unstaged scope returns files', unstaged.files.length > 0, JSON.stringify(unstaged.files.map(/** @param {DiffFile} f */ f => f.path)))
const withHunks = unstaged.files.find(/** @param {DiffFile} f */ f => (f.hunks?.length ?? 0) > 0)
check('at least one file carries hunks', withHunks !== undefined, JSON.stringify(unstaged.files.map(/** @param {DiffFile} f */ f => `${f.path}:${f.hunks?.length ?? 0}`)))
const hunkLines = (withHunks?.hunks ?? []).flatMap(/** @param {{ lines?: ReadonlyArray<string> }} h */ h => h.lines ?? [])
check('hunk lines are patch strings', hunkLines.every((/** @type {unknown} */ l) => typeof l === 'string'), JSON.stringify(hunkLines.slice(0, 3)))
check('an added line is shown', hunkLines.some((/** @type {string} */ l) => l.startsWith('+') && !l.startsWith('+++')), JSON.stringify(hunkLines.slice(0, 6)))

const staged = await localDiff(ctx, config, session, REMOTE_ROOT, null, { kind: 'staged' }, layers, signal)
check('staged scope returns files', Array.isArray(staged.files), `files=${staged.files.length}`)

console.log('\nnew side of a changed file (through ctx.fs)')
const changedPath = withHunks?.path ?? unstaged.files[0]?.path
if (changedPath !== undefined) {
  const text = await localText(ctx, config, session, REMOTE_ROOT, { kind: 'unstaged' }, changedPath, signal)
  check('localText reads the remote working tree', typeof text === 'string' && text.length > 0, JSON.stringify(text.slice(0, 30)))
}

console.log('\nuncommitted scope (untracked files, non-ASCII names)')
const uncommitted = await localDiff(ctx, config, session, REMOTE_ROOT, null, { kind: 'uncommitted' }, layers, signal)
const uncommittedPaths = uncommitted.files.map(/** @param {DiffFile} f */ f => f.path)
check('uncommitted listing parses', uncommittedPaths.length > 0, JSON.stringify(uncommittedPaths))
check('paths are not C-quoted escapes', uncommittedPaths.every((/** @type {string} */ p) => !/^".*"$/.test(p) && !p.includes('\\3')), JSON.stringify(uncommittedPaths))

console.log('\ncompare-with picker')
const git = gitIn(ctx, config, session, REMOTE_ROOT, signal)
const bases = await baseBranches(git, inspection, null, '', 50)
check('baseBranches returns a structure', typeof bases === 'object' && bases !== null)
check('it names at least one branch', JSON.stringify(bases).includes('refs/'), JSON.stringify(bases).slice(0, 100))

console.log(`\nfailures: ${failures}`)
process.exit(failures === 0 ? 0 : 1)
